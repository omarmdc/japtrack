-- V1: initial JapTrack schema, matching the User and Application entity mappings.
--
-- Flyway runs each versioned migration exactly once and records it in flyway_schema_history.
-- Never edit this file after it has been applied to a database; schema changes go in a new V2__..., V3__... file.
--
-- Column names are the lowercase snake_case form of the entity fields (userEmail -> user_email), which is what
-- Spring's default Hibernate naming strategy expects. Identifiers are left unquoted so PostgreSQL keeps them lowercase.
-- Hibernate runs with ddl-auto=validate and refuses to start if these tables don't match the entities.


-- "users" rather than "user": USER is a reserved word in PostgreSQL
CREATE TABLE users (
    -- GenerationType.IDENTITY: the database assigns the ID on insert and Hibernate reads it back
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_name       VARCHAR(255) NOT NULL,
    -- Stored trimmed and lowercased by the application (User.normalizeEmail), so a plain unique constraint
    -- is enough to make emails unique regardless of case
    user_email      VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    user_first_name VARCHAR(255) NOT NULL,
    user_last_name  VARCHAR(255) NOT NULL,
    -- LocalDateTime (no time zone). Hibernate fills both on insert (@CreationTimestamp / @UpdateTimestamp),
    -- so there are no database defaults
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),

    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_user_name UNIQUE (user_name),
    CONSTRAINT uk_users_user_email UNIQUE (user_email)
);


CREATE TABLE applications (
    application_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT       NOT NULL,
    company_name    VARCHAR(255) NOT NULL,
    position_title  VARCHAR(255) NOT NULL,
    job_post_url    VARCHAR(255),
    pay_rate        DOUBLE PRECISION,
    -- Enums are stored by name (@Enumerated(EnumType.STRING)) and are optional, like in the entity
    work_setting    VARCHAR(255),
    work_type       VARCHAR(255),
    employment_type VARCHAR(255),
    status          VARCHAR(255),
    date_applied    DATE         NOT NULL,
    notes           VARCHAR(255),
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),

    CONSTRAINT pk_applications PRIMARY KEY (application_id),

    -- No ON DELETE CASCADE: deleting a user's applications is handled by JPA (CascadeType.ALL on
    -- User.applications), so the database only guarantees that every application has an existing owner
    CONSTRAINT fk_applications_user FOREIGN KEY (user_id) REFERENCES users (user_id),

    -- Only the current Java enum constants are accepted. Adding or renaming a constant needs a new migration
    -- that updates the matching constraint.
    CONSTRAINT ck_applications_work_setting
        CHECK (work_setting IN ('REMOTE', 'ON_SITE', 'HYBRID', 'NOT_SPECIFIED')),
    CONSTRAINT ck_applications_work_type
        CHECK (work_type IN ('FULL_TIME', 'PART_TIME', 'NOT_SPECIFIED')),
    CONSTRAINT ck_applications_employment_type
        CHECK (employment_type IN ('EMPLOYEE', 'FREELANCE', 'NOT_SPECIFIED')),
    CONSTRAINT ck_applications_status
        CHECK (status IN ('APPLIED', 'INTERVIEW', 'GOT_OFFER', 'WITHDRAWN', 'ACCEPTED', 'REJECTED'))
);


-- PostgreSQL does not index foreign key columns automatically. This index matches the owner's application list
-- (WHERE user_id = ? ORDER BY date_applied DESC, application_id DESC), so it can be read in order without a sort,
-- and it also covers the owner-scoped lookups and the user_id check when a user is deleted.
CREATE INDEX idx_applications_user_date_applied
    ON applications (user_id, date_applied DESC, application_id DESC);
